/**
 * Write src/chrome/outliner-version.js from package.json + git HEAD date.
 * Run via `npm run build` (also pretest).
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const majorMinor = String(pkg.version || '0.0.0')
  .split('.')
  .slice(0, 2)
  .join('.');
const updated = execFileSync('git', ['log', '-1', '--format=%cs'], {
  cwd: root,
  encoding: 'utf8',
}).trim();
if (!/^\d{4}-\d{2}-\d{2}$/.test(updated)) {
  throw new Error(`Unexpected git date: ${updated}`);
}

const outPath = join(root, 'src/chrome/outliner-version.js');
const banner =
  '/** Generated by scripts/build-outliner-version.js — do not edit. */\n';
const source =
  `${banner}` +
  `export const OUTLINER_VERSION = ${JSON.stringify(majorMinor)};\n` +
  `export const OUTLINER_UPDATED = ${JSON.stringify(updated)};\n`;

writeFileSync(outPath, source);
console.log(`Wrote ${outPath} (${majorMinor}, updated ${updated})`);
